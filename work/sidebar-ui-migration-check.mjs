  await ev(`document.querySelector('#migration-tab-bot').click()`); await wait(100)
  assert(await ev(`document.querySelector('#migration-tab-bot').getAttribute('aria-selected')==='true' && !document.querySelector('.dsh-footer')`))
  console.log('PASS top mode tabs and content switching')
  for (const theme of ['light', 'dark']) {
    await send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-color-scheme', value: theme }] }, sessionId)
    await ev(`document.body.style.colorScheme='normal'`); await wait(150)
    const expected = theme === 'light' ? 'rgb(255, 255, 255)' : 'rgb(20, 20, 20)'
    assert.equal(await ev(`getComputedStyle(document.querySelector('.migration-grid')).backgroundColor`), expected)
    const shot = await send('Page.captureScreenshot', { format: 'png', captureBeyondViewport: true })
    await writeFile(`/tmp/migration-theme-${theme}.png`, Buffer.from(shot.data, 'base64'))
  }
  await ev(`document.body.style.colorScheme='light'`); await wait(150)
  assert.equal(await ev(`getComputedStyle(document.querySelector('.migration-grid')).backgroundColor`), 'rgb(255, 255, 255)')
  await ev(`document.body.style.colorScheme='dark'`); await wait(150)
  assert.equal(await ev(`getComputedStyle(document.querySelector('.migration-grid')).backgroundColor`), 'rgb(20, 20, 20)')
  console.log('PASS system light/dark + host color-scheme override + live updates')
  await send('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] }, sessionId)
  await click('roster-row-night'); await click('roster-row-aning')
  await ev(`window.changes=0;new MutationObserver(()=>window.changes++).observe(document.querySelector('[data-testid="persona-aning"] .personaEye'),{attributes:true})`)
  await wait(1600); assert(await ev('window.changes>0')); console.log('PASS original Persona rAF animation')
  await click('memory-open'); assert(await ev(`!!document.querySelector('[data-testid="memory-panel"]')`)); await click('memory-close')
  await click('routines-open'); assert(await ev(`!!document.querySelector('[data-testid="routines-form"]')`)); await click('routines-close')
  await click('peers-open'); assert(await ev(`document.querySelector('[data-testid="peers-list"]').textContent.includes('诗人小北')`)); await click('peers-close')
  await ev(`document.querySelector('[data-testid="composer-emoji"]').dispatchEvent(new MouseEvent('mousedown',{bubbles:true,cancelable:true}))`); await wait(100); assert(await ev(`!!document.querySelector('[role="listbox"]')`)); await ev(`document.querySelector('[data-testid="composer-input"]').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`)
  await ev(`(()=>{const e=document.querySelector('[data-testid="composer-input"]');Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(e,'演示原组件的动态回复');e.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  await wait(100); await click('composer-send')
  assert(await ev(`!!document.querySelector('.persona[data-mood="working"]')`)); console.log('PASS working persona and original waiting indicator')
  await wait(1500); assert(await ev(`document.querySelector('[data-testid="transcript"]').textContent.includes('收到')`))
